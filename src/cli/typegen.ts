import { GristClient } from '../client/GristClient';

export interface TypegenColumnFields {
  type?: string;
  label?: string;
  isFormula?: boolean;
  formula?: string;
  [key: string]: unknown;
}

export interface TypegenColumn {
  id: string;
  fields?: TypegenColumnFields;
  [key: string]: unknown;
}

export interface TypegenTable {
  id: string;
  columns: TypegenColumn[];
  [key: string]: unknown;
}

export interface TypegenDocSchema {
  tables: TypegenTable[];
}

/**
 * Maps a Grist column type specification to its corresponding TypeScript type.
 */
export function mapGristTypeToTs(gristType?: string): string {
  if (!gristType || typeof gristType !== 'string') {
    return 'unknown';
  }

  const type = gristType.trim();

  if (type === 'Text' || type === 'String') {
    return 'string';
  }
  if (type === 'Numeric' || type === 'Int' || type === 'Integer' || type === 'ManualSortPos') {
    return 'number';
  }
  if (type === 'Bool' || type === 'Boolean') {
    return 'boolean';
  }
  if (type === 'DateTime' || type.startsWith('DateTime:')) {
    return 'number';
  }
  if (type === 'Date' || type.startsWith('Date:')) {
    return 'string | number';
  }
  if (type === 'Choice') {
    return 'string';
  }
  if (type === 'ChoiceList') {
    return 'string[]';
  }
  if (type === 'Ref' || type.startsWith('Ref:')) {
    return 'number';
  }
  if (type === 'RefList' || type.startsWith('RefList:')) {
    return 'number[]';
  }
  if (type === 'Attachments' || type === 'Attachment') {
    return 'number[]';
  }

  return 'unknown';
}

/**
 * Sanitizes a table ID into a valid TypeScript interface identifier base name.
 */
export function sanitizeInterfaceName(name: string): string {
  if (!name || typeof name !== 'string') {
    return 'Table';
  }
  const cleaned = name.replace(/[^a-zA-Z0-9_$]+/g, '_').replace(/^([0-9])/, '_$1');
  return cleaned || 'Table';
}

/**
 * Formats an object or interface property key, quoting if it contains special characters or spaces.
 */
export function formatPropertyKey(key: string): string {
  if (/^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key)) {
    return key;
  }
  const escaped = key
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t');
  return `'${escaped}'`;
}

/**
 * Generates TypeScript declarations (.d.ts) from a Grist document schema.
 */
export function generateTypeScriptDeclarations(schema: TypegenDocSchema): string {
  const lines: string[] = [
    '/**',
    ' * Auto-generated by grist-typegen. Do not edit manually.',
    ' */',
    '',
  ];

  const tableRegistry: Array<{ tableId: string; interfaceName: string }> = [];
  const usedInterfaceNames = new Set<string>();

  for (const table of schema?.tables || []) {
    const baseName = sanitizeInterfaceName(table.id);
    let interfaceName = `${baseName}Row`;
    let counter = 2;
    while (usedInterfaceNames.has(interfaceName)) {
      interfaceName = `${baseName}_${counter}Row`;
      counter++;
    }
    usedInterfaceNames.add(interfaceName);
    tableRegistry.push({ tableId: table.id, interfaceName });

    lines.push(`export interface ${interfaceName} {`);
    for (const col of table.columns || []) {
      const propKey = formatPropertyKey(col.id);
      const propType = mapGristTypeToTs(col.fields?.type);
      lines.push(`  ${propKey}: ${propType};`);
    }
    lines.push('}');
    lines.push('');
  }

  lines.push('export interface GristTables {');
  for (const { tableId, interfaceName } of tableRegistry) {
    const key = formatPropertyKey(tableId);
    lines.push(`  ${key}: ${interfaceName};`);
  }
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

/**
 * Fetches the document schema (all tables and their columns) using GristClient.
 */
export async function fetchDocSchema(
  client: GristClient,
  docId: string
): Promise<TypegenDocSchema> {
  const tables = await client.raw.tables.list(docId);
  const tableSchemas = await Promise.all(
    tables.map(async (table) => {
      const columns = await client.raw.columns.list(docId, table.id);
      return {
        id: table.id,
        columns: columns.map((col) => ({
          id: col.id,
          fields: col.fields,
        })),
      };
    })
  );

  return { tables: tableSchemas };
}
